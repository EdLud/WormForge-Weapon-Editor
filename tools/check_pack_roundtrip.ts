/**
 * The libraries an export ships, read from `spec/` the way the app imports them
 * with `?raw`. The effects SDK's sheets stay out (an export fetches them, and no
 * weapon here uses effects), so this stays a pure read of two files.
 */
const LIBRARIES: PackLibraries = {
  wfws: {
    modToml: readFileSync('spec/lua_sdk/wfws_sdk/mod.toml', 'utf8'),
    spriteBuilderLua: readFileSync('spec/lua_sdk/wfws_sdk/lib/wfws_sprite_builder.lua', 'utf8'),
  },
};

/** `emitPack` as the app calls it, with the libraries supplied. */
const emitPack = (pack: PackProject) => emitPackFiles(pack, LIBRARIES);

let failures = 0;
let checks = 0;
function ok(what: string, condition: boolean, detail = '') {
  checks += 1;
  if (!condition) {
    failures += 1;
    console.error(`  FAIL ${what}${detail ? `: ${detail}` : ''}`);
  }
}

/**
 * A project the emitter can write without a browser: no hold, no sprite builder,
 * no effects. `createDefaultHoldSheet`/`createDefaultMissileSheet` need a canvas
 * and the effects SDK sheets are fetched, so a Node run has to keep art that is
 * generated by the editor out of the picture.
 */
const bareProject = (patch: Partial<WeaponProject> = {}): WeaponProject => {
  const base = stockDonor('grenade') as Partial<WeaponProject>;
  return {
    ...(base as WeaponProject),
    id: 'wfws.pack.alpha',
    name: 'Alpha',
    version: '0.1.0',
    author: 'Pack Author',
    based_on: 'stock.grenade',
    slot: 'grenade',
    defaults: { ammo: 1, delay: 0, crateChance: 0, crateType: 'weapon', afterUse: '' },
    fireType: 'power',
    hold: { ...(base.hold ?? {}), enabled: false } as WeaponProject['hold'],
    missileSprite: { ...(base.missileSprite ?? {}), enabled: false } as WeaponProject['missileSprite'],
    body: { ...DEFAULT_BODY, ...(base.body ?? {}) },
    action: 'bounce',
    burst: 'nothing',
    recordOverrides: { ...(base.recordOverrides ?? {}) },
    customSprites: {},
    donorBaseline: stockDonorBaseline('grenade'),
    ...patch,
  } as WeaponProject;
};

const pack = (weapons: WeaponProject[]): PackProject => ({
  id: 'wfws.pack',
  name: 'Pack',
  author: 'Pack Author',
  version: '1.0.0',
  description: 'Two weapons in one bundle.',
  weapons,
});

// ---- one emitter: single weapon = pack of one -------------------------------
{
  const project = bareProject();
  ok(
    'a single weapon is a pack of one, manifest for manifest',
    generateModToml(project) === generatePackToml(singleWeaponPack(project)),
  );
  ok(
    'and profile for profile',
    generateProfileToml(project) === generatePackProfile(singleWeaponPack(project)),
  );
  const single = singleWeaponPack(project);
  ok('the pack of one takes the weapon id and name', single.id === project.id && single.name === project.name);
}

// ---- a pack's manifest ------------------------------------------------------
{
  // One weapon asks for `custom.lib`, two ask for it and for `wf.sdk` (a hold):
  // the bundle gets one list, in first-seen order, because a library installs
  // once per bundle.
  const alpha = bareProject({ id: 'wfws.pack.alpha', name: 'Alpha' });
  const beta = bareProject({
    id: 'wfws.pack.beta',
    name: 'Beta',
    slot: 'bazooka',
    hold: { ...(alpha.hold ?? {}), enabled: true, frames: 1 } as WeaponProject['hold'],
    extraDependencies: ['custom.lib'],
  });
  const delta = bareProject({
    id: 'wfws.pack.delta',
    name: 'Delta',
    slot: 'mortar',
    hold: { ...(alpha.hold ?? {}), enabled: true, frames: 1 } as WeaponProject['hold'],
    extraDependencies: ['custom.lib', 'wf.sdk'],
    defaults: { ...alpha.defaults, ammo: -1 },
    options: [
      {
        key: 'direction',
        kind: 'choice',
        choices: ['straight', 'opposite'],
        default: 'straight',
        value: 'opposite',
      },
    ],
  });
  const toml = generatePackToml(pack([alpha, beta, delta]));
  const components = toml.match(/\[\[components\]\]/g) ?? [];
  ok('one [[components]] block per weapon', components.length === 3, String(components.length));
  ok(
    'every weapon id and its own entry',
    toml.includes('id = "wfws.pack.alpha"') &&
      toml.includes('entry = "weapons/alpha.lua"') &&
      toml.includes('entry = "weapons/beta.lua"') &&
      toml.includes('entry = "weapons/delta.lua"'),
    toml.split('\n').filter((line) => line.startsWith('entry')).join(' | '),
  );
  ok(
    'the dependency list is the union, once each, first-seen order',
    toml.includes('dependencies = ["wf.sdk", "custom.lib"]'),
    toml.split(String.fromCharCode(10)).find((line) => line.startsWith('dependencies')) ?? 'none',
  );
  ok(
    'and the header is the pack, not the first weapon',
    toml.startsWith('id = "wfws.pack"') && toml.includes('name = "Pack"'),
    toml.slice(0, 120),
  );
  ok(
    'a weapon’s options stay under its own component',
    toml.indexOf('id = "wfws.pack.delta"') < toml.indexOf('key = "direction"'),
  );

  const profile = generatePackProfile(pack([alpha, beta, delta]));
  ok(
    'one profile places every weapon and every slot it replaces',
    profile.includes('"wfws.pack.alpha" = true') &&
      profile.includes('"wfws.pack.beta" = true') &&
      profile.includes('"wfws.pack.delta" = true') &&
      profile.includes('"stock.bazooka" = true'),
    profile,
  );
  ok(
    'and writes infinite ammo only for the weapon that asked for it',
    (profile.match(/\[weapon_settings\./g) ?? []).length === 1 &&
      profile.includes('[weapon_settings."wfws.pack.delta"]'),
    profile,
  );
  ok(
    'and the changed option value under that weapon’s id',
    profile.includes('[options."wfws.pack.delta"]') && profile.includes('"direction" = "opposite"'),
    profile,
  );
}

// ---- the emitter and the reader agree --------------------------------------
{
  const alpha = bareProject({ id: 'wfws.pack.alpha', name: 'Alpha' });
  const beta = bareProject({ id: 'wfws.pack.beta', name: 'Beta', slot: 'bazooka' });
  const files = await emitPack(pack([alpha, beta]));
  const names = [...files.keys()].sort();
  ok(
    'the emitter writes the pack folder and the library bundles beside it',
    names.every((name) => name.startsWith('pack/') || name.startsWith('wf-lib/')),
    names.join(', '),
  );
  ok(
    'one manifest, one profile, one module per weapon',
    files.has('pack/mod.toml') &&
      files.has('pack/profiles/Pack.toml') &&
      files.has('pack/weapons/alpha.lua') &&
      files.has('pack/weapons/beta.lua'),
    names.join(', '),
  );
  ok(
    'and the library bundle beside it',
    files.has('wf-lib/wfws_sdk/mod.toml') && files.has('wf-lib/wfws_sdk/lib/wfws_sprite_builder.lua'),
  );

  const asModFiles = (): ModFile[] =>
    [...files.entries()].map(([path, content]) =>
      typeof content === 'string'
        ? { path, text: content }
        : { path, text: '', bytes: content },
    );
  const modFiles = asModFiles();
  const bundles = readBundles(modFiles);
  const packBundle = bundles.find((bundle) => bundle.id === 'wfws.pack');
  ok(
    'the map holds the pack and the library bundle it ships',
    !!packBundle && bundles.length === 2,
    bundles.map((bundle) => bundle.id).join(', '),
  );
  ok(
    'and the manifest reads back with one component per weapon',
    packBundle?.components?.length === 2,
    String(packBundle?.components?.length),
  );
  const weapons = readWeapons(bundles, modFiles);
  ok('and the reader finds both weapons', weapons.length === 2, String(weapons.length));
  ok(
    'with the ids and modules the emitter named',
    weapons.some((weapon) => weapon.componentId === 'wfws.pack.alpha' && weapon.modulePath.endsWith('weapons/alpha.lua')) &&
      weapons.some((weapon) => weapon.componentId === 'wfws.pack.beta' && weapon.modulePath.endsWith('weapons/beta.lua')),
    weapons.map((weapon) => `${weapon.componentId}@${weapon.modulePath}`).join(', '),
  );
  ok(
    'each weapon reads a record',
    weapons.every((weapon) => !!weapon.record),
    weapons.map((weapon) => `${weapon.componentId}:${weapon.record ? 'record' : 'none'}`).join(', '),
  );

  // Every declared path has to be a file in the map: a declared sprite without
  // its bytes fails the install of the whole bundle.
  const toml = String(files.get('pack/mod.toml') ?? '');
  const declared = [...toml.matchAll(/\[sprites\."([^"]+)"\]/g)].map((match) => match[1]);
  const missing = declared.filter((path) => !files.has(`pack/${safeBundlePath(path) ?? path}`));
  ok('every declared sprite is in the bundle', missing.length === 0, missing.join(', '));
  const entries = [...toml.matchAll(/entry = "([^"]+)"/g)].map((match) => match[1]);
  ok(
    'and every component entry',
    entries.every((path) => files.has(`pack/${path}`)),
    entries.join(', '),
  );
  ok(
    'the profile is one file the loader will find',
    [...files.keys()].filter((name) => name.endsWith('.toml') && name.includes('/profiles/')).length === 1,
  );

  // Importing what we emitted must come back as the same two weapons.
  const imported = [];
  for (const weapon of weapons) {
    const result = await importBundleWeapon(weapon, modFiles);
    imported.push(result.project);
  }
  ok(
    'and importing the pack gives both weapons back',
    imported.length === 2 && imported.every((project) => !!project.id),
    imported.map((project) => project.id).join(', '),
  );
}

// ---- per-weapon folders are the slug --------------------------------------
{
  const alpha = bareProject({ id: 'wfws.arsenal.alpha', name: 'Alpha' });
  const beta = bareProject({ id: 'wfws.arsenal.beta', name: 'Beta' });
  ok(
    'a weapon folder is the last id segment',
    sanitizeModFolder(alpha.id) === 'alpha' && sanitizeModFolder(beta.id) === 'beta',
  );
  const toml = generatePackToml({ ...pack([alpha, beta]), id: 'wfws.arsenal' });
  ok(
    'so two weapons in one pack never share an entry',
    toml.includes('entry = "weapons/alpha.lua"') && toml.includes('entry = "weapons/beta.lua"'),
  );
}

// ---- art across the pack ---------------------------------------------------
/** A hold sheet declaration in the manifest, whatever folder it names. */
const DECLARED_HOLD = /\[sprites\."[^"]*\/hold\.png"\]/g;
{
  // Two weapons left on the same held art are one sheet, not two, and both
  // modules have to name the one that survived: the alias is applied to each
  // weapon's Lua and to the shared manifest. A `sheetFile` is supplied so the
  // default art is never drawn (that needs a canvas), which is what lets this run
  // as a plain script. Two frames, so the sheet is **declared** and the
  // declarations have to agree before the merge is allowed.
  const png = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const withHold = (id: string, name: string): WeaponProject => {
    const base = bareProject({ id, name });
    return {
      ...base,
      hold: {
        ...(base.hold ?? {}),
        enabled: true,
        frames: 2,
        fps: 15,
        sheetFile: new File([png, png], 'hold.png'),
      } as WeaponProject['hold'],
    } as WeaponProject;
  };
  const alpha = withHold('wfws.pack.alpha', 'Alpha');
  const beta = withHold('wfws.pack.beta', 'Beta');
  const files = await emitPack(pack([alpha, beta]));
  const holds = [...files.keys()].filter((name) => name.endsWith('/hold.png'));
  ok(
    'two weapons on the same art write one sheet',
    holds.length === 1,
    holds.join(', ') || 'none',
  );
  const toml = String(files.get('pack/mod.toml') ?? '');
  ok(
    'and the manifest declares it once, with the frames both weapons asked for',
    (toml.match(DECLARED_HOLD) ?? []).length === 1 &&
      /\]\nframes = 2/.test(toml.slice(toml.search(DECLARED_HOLD))),
    toml.split(String.fromCharCode(10)).filter((line) => line.startsWith('[sprites.')).join(', '),
  );
  // Only the pack's own modules: the library's doc comment also contains
  // `sheet = "sprites/<mod>/hold.png"`.
  const named = [...files.entries()]
    .filter(([name]) => name.startsWith('pack/weapons/') && name.endsWith('.lua'))
    .map(([, body]) => String(body).match(/sheet = "([^"]*hold\.png)"/)?.[1] ?? 'none');
  ok(
    'and both modules name the sheet that survived',
    named.length === 2 && named.every((path) => holds.includes(`pack/${path}`)),
    named.join(', '),
  );
  ok(
    'and the sheet is where the module says it is',
    holds.length === 1 && holds[0] === `pack/${named[0]}`,
    `${holds[0]} vs pack/${named[0]}`,
  );
}

// ---- two records with one file name ---------------------------------------
{
  // A pack has one `weps/` folder, so two weapons built from a `.wep` both called
  // `weapon.wep` would write one file: the second export would quietly hand one
  // weapon the other's record. Each weapon of a pack names its own folder, and a
  // pack of one leaves the path exactly as it was.
  const wepBytes = new Uint8Array([6, 0xdd, 0xbb, 0x5a]);
  const alpha = bareProject({
    id: 'wfws.pack.alpha',
    name: 'Alpha',
    useWepFile: true,
    wepFile: new File([wepBytes], 'weapon.wep'),
  });
  const beta = bareProject({
    id: 'wfws.pack.beta',
    name: 'Beta',
    slot: 'bazooka',
    useWepFile: true,
    wepFile: new File([wepBytes], 'weapon.wep'),
  });
  ok(
    'a single weapon keeps its `weps/` file at the root',
    wepBundlePath({ ...alpha, packSlug: undefined }) === 'weps/weapon.wep',
    String(wepBundlePath({ ...alpha, packSlug: undefined })),
  );
  const files = await emitPack(pack([alpha, beta]));
  ok(
    'two weapons of a pack write two records',
    files.has('pack/weps/alpha/weapon.wep') && files.has('pack/weps/beta/weapon.wep'),
    [...files.keys()].filter((name) => name.endsWith('.wep')).join(', '),
  );
  for (const slug of ['alpha', 'beta']) {
    const lua = String(files.get(`pack/weapons/${slug}.lua`) ?? '');
    ok(
      `and ${slug}.lua names its own`,
      lua.includes(`wep = "weps/${slug}/weapon.wep"`),
      lua.split(String.fromCharCode(10)).find((line) => line.includes('wep = ')) ?? 'no wep line',
    );
  }
}

// ---- reading a pack back (P5) -------------------------------------------
{
  // The round trip in its strongest form: what the emitter writes, read as a pack.
  const alpha = bareProject({ id: 'wfws.pack.alpha', name: 'Alpha' });
  const beta = bareProject({ id: 'wfws.pack.beta', name: 'Beta', slot: 'bazooka' });
  const files = await emitPack(pack([alpha, beta]));
  const modFiles: ModFile[] = [...files.entries()].map(([path, content]) =>
    typeof content === 'string'
      ? { path, text: content }
      : { path, text: '', bytes: content },
  );
  const bundles = readBundles(modFiles);
  const source = bundles.find((bundle) => bundle.id === 'wfws.pack');
  const weapons = readWeapons(bundles, modFiles).filter((weapon) => weapon.record);
  const imported = await importBundlePack(source!, weapons, modFiles);
  ok(
    'an exported pack reads back as a pack',
    imported.pack.weapons.length === 2 && imported.pack.id === 'wfws.pack',
    `${imported.pack.id}: ${imported.pack.weapons.length}`,
  );
  ok(
    'with the ids the manifest declared, in order',
    imported.pack.weapons.map((weapon) => weapon.id).join(',') === 'wfws.pack.alpha,wfws.pack.beta',
    imported.pack.weapons.map((weapon) => weapon.id).join(','),
  );
  ok(
    'and the names, slots and profile its own manifest wrote',
    imported.pack.weapons[0].name === 'Alpha' &&
      imported.pack.weapons[1].slot === 'bazooka' &&
      imported.pack.profileName === 'Pack' &&
      imported.pack.version === '1.0.0',
    `${imported.pack.weapons[0].name}/${imported.pack.weapons[1].slot}/${imported.pack.profileName}`,
  );
  // Re-exporting what was read must be the same bundle, not a renamed copy.
  const again = await emitPack(imported.pack);
  const againToml = String(again.get('pack/mod.toml') ?? '');
  ok(
    'and re-exporting it writes the same two components',
    (againToml.match(/\[\[components\]\]/g) ?? []).length === 2 &&
      againToml.includes('id = "wfws.pack.alpha"') &&
      againToml.includes('id = "wfws.pack.beta"'),
    againToml,
  );

  // A foreign bundle keeps its own ids installed, so an import namespaces them
  // under a copy of the source's own id: two bundles claiming one weapon id is
  // refused by the engine, and the source author's namespace is kept rather than
  // replaced by one of ours. The `_import` marker is in the **last** segment,
  // because that segment is the folder the bundle writes into.
  const foreignModToml = String(files.get('pack/mod.toml') ?? '')
    .split('id = "wfws.pack"')
    .join('id = "px.ports"')
    .split('id = "wfws.pack.alpha"')
    .join('id = "px.port"')
    .split('id = "wfws.pack.beta"')
    .join('id = "px.other"');
  const foreignFiles: ModFile[] = [
    { path: 'ports/mod.toml', text: foreignModToml },
    ...modFiles
      .filter((file) => file.path.startsWith('pack/') && file.path !== 'pack/mod.toml')
      .map((file) => ({ ...file, path: file.path.replace(/^pack\//, 'ports/') })),
  ];
  const foreignBundles = readBundles(foreignFiles);
  const foreignSource = foreignBundles.find((bundle) => bundle.id === 'px.ports');
  const foreignWeapons = readWeapons(foreignBundles, foreignFiles).filter((weapon) => weapon.record);
  const foreign = await importBundlePack(foreignSource!, foreignWeapons, foreignFiles);
  ok(
    'a foreign bundle is imported under a copy of its own namespace',
    foreign.pack.id === 'px.ports_import' &&
      foreign.pack.weapons.map((weapon) => weapon.id).join(',') ===
        'px.ports_import.port,px.ports_import.other',
    `${foreign.pack.id}: ${foreign.pack.weapons.map((weapon) => weapon.id).join(',')}`,
  );
  ok(
    'and says so once',
    foreign.notes.some((note) => note.includes('imported as px.ports_import')),
    foreign.notes.join(' | '),
  );
  ok(
    'two components with one slug are told apart',
    adoptWeaponId(
      { ...foreign.pack, weapons: [foreign.pack.weapons[0]] },
      'px.ports_import.port',
    ) === 'px.ports_import.port_2',
    adoptWeaponId({ ...foreign.pack, weapons: [foreign.pack.weapons[0]] }, 'px.ports_import.port'),
  );
  // An editor-written bundle keeps its ids: it already lives under its own bundle
  // id, so a re-import is the same pack with the same art folders.
  ok(
    'our own bundle keeps the ids it declares',
    packIdFromBundle('wfws.pack', ['wfws.pack.alpha', 'wfws.pack.beta']) === 'wfws.pack',
    packIdFromBundle('wfws.pack', ['wfws.pack.alpha']),
  );
  ok(
    'a bundle whose weapons name another namespace is copied',
    packIdFromBundle('wfws.pack', ['px.port']) === 'wfws.pack_import',
    packIdFromBundle('wfws.pack', ['px.port']),
  );
}

// ---- the pack's own rules (add, duplicate, remove, move) ------------------
{
  // Ids are allocated once, and the bump lives in the **folder** segment: a
  // `rocket.2` would be folder `2` and would collide with another weapon's `2`,
  // which is the one collision that silently swaps two weapons' art.
  const empty: PackProject = { id: 'wfws.arsenal', name: 'Arsenal', author: 'A', version: '1.0.0', weapons: [] };
  ok('a new weapon names its pack and slug', newWeaponId(empty, 'Heavy Rocket!') === 'wfws.arsenal.heavy_rocket');
  const rocket = bareProject({ id: 'wfws.arsenal.rocket', name: 'Rocket' });
  ok(
    'a taken folder bumps inside the slug',
    newWeaponId({ ...empty, weapons: [rocket] }, 'Rocket') === 'wfws.arsenal.rocket_2',
    newWeaponId({ ...empty, weapons: [rocket] }, 'Rocket'),
  );
  ok('a taken name bumps too', uniqueWeaponName({ ...empty, weapons: [rocket] }, 'rocket') === 'rocket 2');

  // The bundle id is the namespace, so renaming it renames its weapons with it:
  // an old prefix would be refused by `validateBundle` (`old.rocket` is not under
  // `new`) for a reason the author cannot see from the card.
  const nsPack: PackProject = {
    ...empty,
    id: 'wfws.arsenal',
    weapons: [
      bareProject({ id: 'wfws.arsenal.rocket', name: 'Rocket' }),
      bareProject({ id: 'wfws.arsenal.laser', name: 'Laser' }),
      bareProject({ id: 'px.foreign', name: 'Foreign' }),
    ],
  };
  const renamed = renamespaceWeapons(nsPack, 'wfws.arsenal', 'lucia.arsenal');
  ok(
    'renaming a bundle re-namespaces the weapons under it and leaves a foreign id alone',
    renamed.weapons.map((weapon) => weapon.id).join(',') ===
      'lucia.arsenal.rocket,lucia.arsenal.laser,px.foreign',
    renamed.weapons.map((weapon) => weapon.id).join(','),
  );
  ok(
    'and the rename does not touch the art folders, which are the last segment',
    renamed.weapons[0].id.split('.').pop() === 'rocket',
  );

  // A bundle of one is that weapon, so its export stays `<weapon>.zip`.
  const one = syncPackToSoleWeapon({
    ...empty,
    id: 'wfws.grenade',
    name: 'Grenade',
    author: 'Old',
    weapons: [bareProject({ id: 'wfws.grenade', name: 'Grenade' })],
  });
  ok(
    'one weapon gives the bundle its identity',
    one.id === 'wfws.grenade' && one.name === 'Grenade' && one.author === one.weapons[0].author,
    `${one.id}/${one.name}/${one.author}`,
  );
  const two = addWeaponToPack(one, { ...bareProject({ name: 'Heavy Rocket' }), id: 'whatever' });
  ok(
    'the second weapon joins under the bundle id',
    two.pack.weapons.length === 2 && two.pack.weapons[1].id === 'wfws.grenade.heavy_rocket',
    two.pack.weapons.map((weapon) => weapon.id).join(', '),
  );
  ok(
    'and the bundle keeps the identity it had',
    two.pack.id === 'wfws.grenade' && two.pack.name === 'Grenade',
    `${two.pack.id}/${two.pack.name}`,
  );
  ok('the added weapon is selected', two.index === 1);

  // Duplicating moves the copy's declared art to its own folder, or the two
  // weapons would name the same sheet and one would draw the other's art.
  const withArt = {
    ...bareProject({ id: 'wfws.arsenal.rocket', name: 'Rocket' }),
    hold: { enabled: true, sheet: 'sprites/rocket/hold.png' } as WeaponProject['hold'],
    missileSprite: { enabled: true, mode: 'custom', sheet: 'sprites/rocket/missile.png' } as WeaponProject['missileSprite'],
    customSprites: {
      x: { purpose: 'trail', name: 'x', path: 'sprites/rocket/trail.png', previewUrl: '', frames: 1, fps: 15, play: 'loop' },
    },
    carriedLua: {
      preamble: [
        {
          origin: 'preamble',
          text: 'local HOLE = "sprites/rocket/hole.png"',
          declares: ['HOLE'],
          requires: [],
          line: 1,
          neededBy: ['on_explode'],
        },
      ],
      prologue: [],
      unresolved: [],
      hooks: [
        {
          key: 'on_fire',
          text: 'function(ev) wa.sound.play(ev.worm, "sounds/rocket/x.wav", 5) end',
          line: 2,
        },
      ],
      registrations: [],
      art: { sprites: ['sprites/rocket/hole.png'], sounds: ['sounds/rocket/x.wav'] },
    },
  } as WeaponProject;
  const dup = duplicateWeaponInPack({ ...empty, weapons: [withArt] }, 0);
  const copy = dup.pack.weapons[1];
  ok('a copy gets its own id and name', copy.id === 'wfws.arsenal.rocket_copy' && copy.name === 'Rocket copy', `${copy.id}/${copy.name}`);
  ok(
    'and every path it declares moves with it',
    copy.hold?.sheet === 'sprites/rocket_copy/hold.png' &&
      copy.missileSprite?.sheet === 'sprites/rocket_copy/missile.png' &&
      copy.customSprites.x?.path === 'sprites/rocket_copy/trail.png' &&
      copy.carriedLua?.art?.sprites[0] === 'sprites/rocket_copy/hole.png' &&
      copy.carriedLua?.art?.sounds[0] === 'sounds/rocket_copy/x.wav' &&
      !!copy.carriedLua?.preamble[0]?.text.includes('sprites/rocket_copy/hole.png') &&
      !!copy.carriedLua?.hooks?.[0]?.text.includes('sounds/rocket_copy/x.wav'),
    `${copy.hold?.sheet} ${copy.missileSprite?.sheet} ${copy.customSprites.x?.path} ${copy.carriedLua?.art?.sprites[0]} ${copy.carriedLua?.art?.sounds[0]}`,
  );
  ok('and the original is untouched', dup.pack.weapons[0].hold?.sheet === 'sprites/rocket/hold.png');

  // Order is the manifest's order, and the active index follows the row.
  const three = ['a', 'b', 'c'].reduce(
    (acc, name) => addWeaponToPack(acc, bareProject({ id: '', name: name.toUpperCase() })).pack,
    empty,
  );
  const moved = moveWeaponInPack(three, 0, 1);
  ok(
    'a weapon moves down one place',
    moved.pack.weapons.map((weapon) => weapon.name).join(',') === 'B,A,C' && moved.index === 1,
    moved.pack.weapons.map((weapon) => weapon.name).join(','),
  );
  ok('and a move off the end is refused', moveWeaponInPack(three, 2, 1).index === 2);
  const removed = removeWeaponFromPack(three, 1);
  ok(
    'removing a weapon keeps the rest in order and lands on the neighbour',
    removed.pack.weapons.map((weapon) => weapon.name).join(',') === 'A,C' && removed.index === 0,
    `${removed.pack.weapons.map((weapon) => weapon.name).join(',')} @${removed.index}`,
  );
  const lastOne = removeWeaponFromPack(one, 0);
  ok('a bundle always keeps one weapon', lastOne.pack.weapons.length === 1 && lastOne.index === 0);

  // `withWeapon` is how every panel edit reaches the bundle.
  const edited = withWeapon(one, 0, { ...one.weapons[0], name: 'Renamed' });
  ok(
    'an edit reaches the weapon and, while it is alone, the bundle',
    edited.weapons[0].name === 'Renamed' && edited.name === 'Renamed',
    `${edited.weapons[0].name}/${edited.name}`,
  );
  const editedPack = withWeapon(two.pack, 1, { ...two.pack.weapons[1], name: 'Edited' });
  ok(
    'and a two-weapon bundle keeps its own identity',
    editedPack.name === 'Grenade' && editedPack.weapons[1].name === 'Edited',
    `${editedPack.name}/${editedPack.weapons[1].name}`,
  );
}

// ---- a broken pack is refused by name -------------------------------------
{
  // The engine refuses the whole bundle for one bad component, so the emitter has
  // to refuse it first and say which: an export that writes and then fails at
  // load is a report from a player, not from the editor.
  const once = bareProject({ id: 'wfws.pack.twice', name: 'Twice' });
  let message = '';
  try {
    await emitPack(pack([once, { ...once, name: 'Twice Again' }]));
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'a duplicate id is refused, naming the weapon',
    message.includes('wfws.pack.twice is declared twice'),
    message || 'no error',
  );

  const missing = new Map<string, string | Uint8Array>();
  const manifest = [
    '[[components]]',
    'id = "wfws.pack.alpha"',
    'entry = "weapons/alpha.lua"',
    '',
    '[sprites."sprites/pack/hold.png"]',
    'frames = 1',
    '',
  ].join('\n');
  try {
    validateBundle(missing, pack([bareProject()]), manifest, 'pack');
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'and a declared path with no file is refused, naming the path',
    message.includes('`weapons/alpha.lua` is not in the bundle') &&
      message.includes('`sprites/pack/hold.png` is not in the bundle'),
    message || 'no error',
  );

  // P3's other half: a weapon whose generated code raises at load refuses the
  // export, and the message has to say which weapon and which rule. A `math.random`
  // in a custom hook is the case an author hits: the sandbox nils it.
  const dice = bareProject({
    id: 'wfws.pack.dice',
    name: 'Dice',
    enableCustomLua: true,
    customLuaSnippet: 'on_explode = function(ev)\n  local roll = math.random(6)\nend',
  });
  try {
    await emitPack(pack([dice]));
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'code that raises at load refuses the export, naming the weapon and the rule',
    message.includes('Dice') && message.includes('lockstep-rng') && message.includes('line'),
    message || 'no error',
  );
  ok(
    'and the refusal says the bundle would not load',
    message.includes('this bundle would not load'),
    message || 'no error',
  );

  // An id outside the editor's namespace would collide with an installed bundle.
  const foreignId = bareProject({ id: 'px.something', name: 'Foreign' });
  try {
    await emitPack(pack([foreignId]));
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'an id outside the bundle id is refused',
    message.includes("px.something is not under the bundle's id (wfws.pack)"),
    message || 'no error',
  );

  // One path declared twice is a TOML error, not a merge: the engine loses the
  // declaration and `wa.on.draw` fails with a nil.
  const twice = new Map<string, string | Uint8Array>([
    ['pack/weapons/alpha.lua', 'return {}'],
    ['pack/sprites/pack/hold.png', new Uint8Array([1])],
  ]);
  const twiceManifest = [
    '[[components]]',
    'id = "wfws.pack.alpha"',
    'entry = "weapons/alpha.lua"',
    '',
    '[sprites."sprites/pack/hold.png"]',
    'frames = 1',
    '',
    '[sprites."sprites/pack/hold.png"]',
    'frames = 2',
    '',
  ].join(String.fromCharCode(10));
  try {
    validateBundle(twice, pack([bareProject()]), twiceManifest, 'pack');
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'one sheet declared twice is refused',
    message.includes('`sprites/pack/hold.png` is declared 2 times'),
    message || 'no error',
  );

  // Two distinct weapon ids whose last segment collides overwrite the same Lua module and sprite folder.
  const folderClashA = bareProject({ id: 'wfws.pack.a.bomb', name: 'Bomb A' });
  const folderClashB = bareProject({ id: 'wfws.pack.b.bomb', name: 'Bomb B' });
  try {
    await emitPack(pack([folderClashA, folderClashB]));
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'colliding output folders across distinct ids are refused',
    message.includes('shares output folder `bomb`'),
    message || 'no error',
  );

  // Requiring a known SDK module without its bundle dependency is refused at export.
  const missingDep = bareProject({
    id: 'wfws.pack.missing_dep',
    name: 'Missing Dep',
    carriedLua: {
      preamble: [
        {
          origin: 'preamble',
          text: 'local trail = require("wf-lib/effects/trail")',
          declares: ['trail'],
          requires: ['wf-lib/effects/trail'],
          line: 1,
          neededBy: ['on_explode'],
        },
      ],
      prologue: [],
      unresolved: [],
      hooks: [],
      registrations: [],
    },
  });
  try {
    await emitPack(pack([missingDep]));
    message = '';
  } catch (error) {
    message = (error as Error).message;
  }
  ok(
    'an undeclared SDK require refuses the export',
    message.includes('undeclared-require'),
    message || 'no error',
  );
}

if (failures > 0) {
  console.error(`\npack round trip: ${failures} of ${checks} checks failed`);
  process.exit(1);
}
console.log(`pack round trip: all checks passed (${checks} cases)`);
