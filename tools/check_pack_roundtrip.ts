/**
 * Dev-only: a pack the editor writes is a pack the editor reads (P0/P1/P2 of
 * `reqs/pack_export_plan.md`, no server, exits 1 on a failure).
 *
 *   bun run tools/check_pack_roundtrip.ts
 *
 * Three things are asserted here, because they are the three that break quietly:
 *
 *  - **One emitter.** A single-weapon export is `emitPack` of a pack of one, so
 *    the pack path cannot drift from what an export writes. The manifest and the
 *    profile are compared against the single-weapon generators file for file.
 *  - **A pack's manifest.** One `[[components]]` per weapon, ids and entries
 *    distinct, the dependency list the **union** of what the weapons need (no
 *    repeats: a library installs once per bundle), one profile placing every
 *    weapon.
 *  - **The round trip.** The emitted file map is read back with the bundle
 *    reader: N components, N weapons, the same ids, and every declared path
 *    present in the map. A declared sprite without its file fails the whole
 *    bundle at load, and one bad component takes the other N-1 with it.
 */
